<?php

namespace Kiwi\Contao\DesignerBundle\Service;

use Contao\LayoutModel;
use Contao\System;
use Contao\ThemeModel;
use Kiwi\Contao\DesignerBundle\Models\ColorSchemeModel;
use Symfony\Component\Filesystem\Filesystem;
use Twig\Environment;

/**
 * Writes files/themes/_schemes.scss from the color schemes and the layouts' scheme
 * assignments, only when the content differs from the current file.
 */
class SchemesFileRegenerator
{
    private const TWIG_TEMPLATE   = '@KiwiDesigner/schemes.scss.twig';
    private const RELATIVE_TARGET = '/files/themes/_schemes.scss';

    public function __construct(
        private readonly Filesystem $filesystem,
        private readonly Environment $twig,
        private readonly string $projectDir,
        private readonly ?ThemeStylesInvalidator $invalidator = null,
    ) {}

    /**
     * @return bool true if the file was (re)written, false on no-op.
     *
     * @throws \Symfony\Component\Filesystem\Exception\IOException if the file cannot be written
     */
    public function regenerate(): bool
    {
        $targetFile = $this->projectDir . self::RELATIVE_TARGET;
        $targetDir = \dirname($targetFile);

        if (!$this->filesystem->exists($targetDir)) {
            $this->filesystem->mkdir($targetDir);
        }

        $arrLayoutSchemes = [];
        foreach (LayoutModel::findAll() ?? [] as $objLayout) {
            $objTheme = ThemeModel::findByPk($objLayout->pid);
            $arrLayoutSchemes["$objTheme->alias--$objLayout->alias"] = ColorSchemeModel::findByPk($objLayout->scheme)->alias ?? '';
        }

        $rendered = $this->twig->render(self::TWIG_TEMPLATE, [
            'layoutSchemes' => $arrLayoutSchemes,
            'schemes' => ColorSchemeModel::findAll()?->fetchAll() ?? [],
            'props' => $GLOBALS['scheme']['fields'] ?? [],
        ]);

        if (isset($GLOBALS['TL_HOOKS']['alterSchemesScss']) && \is_array($GLOBALS['TL_HOOKS']['alterSchemesScss'])) {
            foreach ($GLOBALS['TL_HOOKS']['alterSchemesScss'] as $callback) {
                $rendered = System::importStatic($callback[0])->{$callback[1]}($rendered);
            }
        }

        $rendered = "// This file is autogenerated. Do not change its contents, it will be overwritten.\n\n" . $rendered;

        $current = $this->filesystem->exists($targetFile) ? file_get_contents($targetFile) : null;

        if ($current === $rendered) {
            return false;
        }

        $this->filesystem->dumpFile($targetFile, $rendered);

        $this->invalidator?->invalidate();

        return true;
    }
}
